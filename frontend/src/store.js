// Объект, содержащий все данные состояния приложения.
const state = {
  // Текущий авторизованный пользователь
  // null, если пользователь не авторизован
  user: null,
  
  // Количество товаров в корзине
  cartCount: 0,
  
  // Полный список товаров в корзине
  // Используется на странице корзины и при оформлении заказа
  cartItems: [],
  
  // Состояние корзины-шторки (drawer): открыта (true) или закрыта (false)
  cartOpen: false,
  
  // Множество функций-подписчиков (listeners), которые вызываются при любом изменении состояния.
  // Используем Set для автоматического устранения дубликатов
  listeners: new Set(),
};

// Экспортируемый объект store с публичным API для работы с состоянием
export const store = {
  
  // Получает значение из состояния по ключу.

  get(key) { 
    return state[key]; 
  },

  
  // Устанавливает новое значение в состояние и уведомляет всех подписчиков.

  set(key, value) {
    // Обновляем значение в состоянии
    state[key] = value;
    
    // Уведомляем всех подписчиков об изменении
    // Передаем ключ и новое значение для возможности точечного обновления UI
    state.listeners.forEach(fn => fn(key, value));
  },

  
  // Подписывается на изменения состояния.

  subscribe(fn) {
    // Добавляем функцию в множество подписчиков
    state.listeners.add(fn);
    
    // Возвращаем функцию для отписки
    // При вызове удаляет подписчика из множества
    return () => state.listeners.delete(fn);
  },

  /**
   * Загружает данные авторизации из localStorage при старте приложения.
   */
  loadAuth() {
    // Пытаемся получить сохраненные данные авторизации
    const auth = localStorage.getItem('witcher_auth');
    
    if (auth) {
      // Если данные есть — парсим JSON
      const parsed = JSON.parse(auth);
      
      // Извлекаем пользователя и сохраняем в состояние
      // Токены остаются в localStorage
      state.user = parsed.user;
    }
  },

  
  // Устанавливает данные авторизации (вход или выход).

  setAuth(data) {
    if (data) {
      // Сохраняем данные (включая токены) в localStorage
      localStorage.setItem('witcher_auth', JSON.stringify(data));
      
      // Сохраняем информацию о пользователе в состояние
      state.user = data.user;
    } else {
      // Удаляем данные авторизации из localStorage
      localStorage.removeItem('witcher_auth');
      
      // Обнуляем пользователя в состоянии
      state.user = null;
    }
    
    // Уведомляем всех подписчиков об изменении user
    // Это позволит перерисовать шапку, обновить защищенные маршруты и т.д.
    state.listeners.forEach(fn => fn('user', state.user));
  },

   // Проверяет, авторизован ли пользователь.

  isAuthenticated() {
    // Преобразуем user в булево значение: !!null = false, !!{...} = true
    return !!state.user;
  },

   // Переключает состояние корзины-шторки (открыта/закрыта).

  toggleCart(open) {
    // Если open передан - устанавливаем его, иначе инвертируем текущее состояние
    state.cartOpen = open ?? !state.cartOpen;
    
    // Уведомляем подписчиков об изменении состояния корзины
    // Компонент CartDrawer отреагирует и покажет/скроет шторку
    state.listeners.forEach(fn => fn('cartOpen', state.cartOpen));
  }
};
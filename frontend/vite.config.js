// defineConfig — это вспомогательная функция, которая обеспечивает автодополнение (IntelliSense)
import { defineConfig } from 'vite';

// Экспортируем объект конфигурации, обернутый в defineConfig.
// Vite прочитает этот файл при запуске dev-сервера или при сборке проекта.
export default defineConfig({
  // root: указывает корневую директорию проекта.
  // В этой папке Vite будет искать index.html и другие статические файлы.
  root: '.',
  
  // css: раздел для настройки обработки CSS-препроцессоров
  css: {
    // preprocessorOptions: настройки для конкретных препроцессоров
    preprocessorOptions: {
      // scss: настройки для SCSS/Sass
      scss: {
        // additionalData: позволяет добавить глобальный SCSS-код в каждый файл .scss перед компиляцией.
        // Например, можно импортировать миксины, переменные или функции, чтобы не писать их в каждом файле.
        // Пустая строка означает, что никакой глобальный код не добавляется.
        additionalData: ''
      }
    }
  },
  
  // server: настройки для режима разработки (npm run dev)
  server: {
    // port: порт, на котором будет запущен dev-сервер.
    // 5173 — стандартный порт Vite (по умолчанию).
    port: 5173,
    
    // proxy: настройка прокси-сервера для перенаправления запросов.
    // Это решает проблему CORS (Cross-Origin Resource Sharing) при разработке,
    // когда фронтенд и бэкенд работают на разных портах/доменах.
    proxy: {
      // Все запросы, начинающиеся с '/api', будут перехвачены и перенаправлены.
      '/api': {
        // target: адрес, на который будут перенаправляться запросы.
        // http://localhost:5117 — предположительно, это адрес вашего бэкенд-сервера (например, ASP.NET Core, Node.js).
        target: 'http://localhost:5117',
        
        // changeOrigin: изменяет заголовок Origin в запросе на целевой хост.
        // Некоторые серверы проверяют этот заголовок для предотвращения поддельных запросов.
        // true — подменяет Origin на 'http://localhost:5117', что позволяет проходить проверки CORS на бэкенде.
        changeOrigin: true
      }
    }
  },
  
  // build: настройки для продакшн-сборки (npm run build)
  build: {
    // outDir: директория, в которую будет собрана готовая сборка.
    // 'dist' — стандартное название для директории с продакшн-кодом.
    outDir: 'dist',
    
    // emptyOutDir: если true, Vite очистит директорию outDir перед сборкой.
    // Это гарантирует, что в папке dist не останется старых файлов от предыдущих сборок.
    emptyOutDir: true
  }
});